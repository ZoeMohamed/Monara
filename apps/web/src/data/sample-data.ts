type HistoryRow = [
  merchant: string,
  category: string | null,
  amount: number,
  date: string,
  time: string,
  method: string,
  emoji: string,
  kind?: "expense" | "income" | "exclusion",
];

function history(rows: HistoryRow[]): Transaction[] {
  return rows.map(([merchant, category, amount, date, time, method, emoji, kind], index) => ({
    id: `00000000-0000-4000-8000-000000000${301 + index}`,
    merchant,
    category,
    amount,
    date,
    time,
    method,
    emoji,
    confidence: null,
    status: "confirmed",
    kind: kind ?? "expense",
    currency: "IDR",
  }));
}

